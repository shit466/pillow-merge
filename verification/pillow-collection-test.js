const assert=require('node:assert/strict');
const {Collection,KEY}=require('./pillow-collection.js');
const {Game}=require('./pillow-engine.js');
const stages=require('./stages.json');
const data=new Map(),storage={getItem:k=>data.get(k),setItem:(k,v)=>data.set(k,v)};
const collection=new Collection(storage,11);
assert.equal(collection.isUnlocked(10),false);
for(let i=0;i<10;i++)assert.equal(collection.isUnlocked(i),true);
for(let i=0;i<9;i++)assert.equal(collection.recordMerge(i),false);
assert.equal(collection.isUnlocked(10),false,'lower merges do not reveal ultimate');
const g=new Game(stages,{onMerge:({tier})=>collection.recordMerge(tier)});g.start();
g.add(9,200,350);g.add(9,201,350);g.step(1/120);
assert.equal(g.highest,10,'two level-10 bodies actually collide and create level 11');
assert.equal(collection.isUnlocked(10),true);
assert.equal(data.get(KEY),'1');
g.reset();assert.equal(collection.isUnlocked(10),true,'new game keeps discovery');
assert.equal(new Collection(storage,11).isUnlocked(10),true,'reload restores discovery');
const blockedStorage={getItem:()=>{throw Error('blocked');},setItem:()=>{throw Error('blocked');}};
const ephemeral=new Collection(blockedStorage,11);ephemeral.recordMerge(9);assert.equal(ephemeral.isUnlocked(10),true);
console.log('PASS: locked by default; lower tiers stay locked; real 10+10 collision unlocks; reset/reload persist; storage-blocked browser works in memory.');
